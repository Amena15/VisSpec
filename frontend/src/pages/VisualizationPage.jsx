import React, { useState, useEffect, useMemo, useRef } from 'react';
import {
  ArrowLeft,
  Download,
  ZoomIn,
  ZoomOut,
  RotateCcw,
  Filter,
  ChevronDown,
  AlertTriangle,
  FileText,
  Play
} from 'lucide-react';
import { useParams, useNavigate, useLocation } from 'react-router-dom';
import { toast } from 'sonner';
import DiagramViewer from '../components/DiagramViewer';
import { ieeeDiagramsAPI, documentAPI, diagramsAPI } from '../services/api';
import plantumlEncoder from 'plantuml-encoder';

const VisualizationPage = () => {
  const { id: routeDocumentId } = useParams();
  const navigate = useNavigate();
  const location = useLocation();

  const queryParams = useMemo(() => new URLSearchParams(location.search), [location.search]);
  const deepLinkHighlight = (queryParams.get('highlight') || '').trim();
  const deepLinkNodeType = (queryParams.get('nodeType') || '').trim();
  const deepLinkSource = (queryParams.get('source') || '').trim();
  const requestedDiagram = (queryParams.get('diagram') || '').trim().toLowerCase();
  const isTraceabilityDeepLink = deepLinkSource === 'traceability';

  const [diagramType, setDiagramType] = useState('usecase');
  const [selectedScenario, setSelectedScenario] = useState('');
  const [scenarios, setScenarios] = useState([]);
  const [currentDiagram, setCurrentDiagram] = useState(null);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [zoomLevel, setZoomLevel] = useState(100);
  const [error, setError] = useState(null);

  // Diagram node click state
  const [linkedRequirements, setLinkedRequirements] = useState([]);
  const [showNodeRequirementsModal, setShowNodeRequirementsModal] = useState(false);

  const [documents, setDocuments] = useState([]);

  const [selectedDocument, setSelectedDocument] = useState(routeDocumentId || '');
  const autoGeneratedDeepLinkRef = useRef('');

  useEffect(() => {
    if (routeDocumentId) {
      setSelectedDocument(routeDocumentId);
    }
  }, [routeDocumentId]);

  useEffect(() => {
    if (requestedDiagram === 'sequence' || requestedDiagram === 'usecase') {
      setDiagramType(requestedDiagram);
    }
  }, [requestedDiagram]);

  useEffect(() => {
    const fetchDocuments = async () => {
      try {
        const res = await documentAPI.getAll();
        setDocuments(res.data || []);
      } catch (err) {
        toast.error('Could not load documents');
      }
    };
    fetchDocuments();
  }, []);

  useEffect(() => {
    if (!selectedDocument || selectedDocument === 'undefined' || selectedDocument === '') {
      setError('Please select a document to visualize.');
      setLoading(false);
      return;
    }
    setCurrentDiagram(null);
    setLoading(false);
  }, [selectedDocument, diagramType]);

  useEffect(() => {
    if (diagramType !== 'sequence' || !selectedDocument) return;
    
    const fetchScenarios = async () => {
      try {
        const res = await diagramsAPI.getScenarios(selectedDocument);
        const scenarioList = res.data.scenarios || [];
        setScenarios(scenarioList);
        if (scenarioList.length > 0 && !selectedScenario) {
          setSelectedScenario(scenarioList[0].id);
        }
      } catch (err) {
        setScenarios([]);
      }
    };
    fetchScenarios();
  }, [diagramType, selectedDocument]);

  useEffect(() => {
    if (!isTraceabilityDeepLink || diagramType !== 'sequence' || !deepLinkHighlight || scenarios.length === 0) return;

    const normalizedHighlight = deepLinkHighlight.toLowerCase();
    const preferredScenario = scenarios.find((scenario) =>
      String(scenario?.name || '').toLowerCase().includes(normalizedHighlight),
    );

    if (preferredScenario?.id && preferredScenario.id !== selectedScenario) {
      setSelectedScenario(preferredScenario.id);
    }
  }, [isTraceabilityDeepLink, diagramType, deepLinkHighlight, scenarios, selectedScenario]);

  const handleGenerateDiagram = async (options = {}) => {
    const {
      targetDocument = selectedDocument,
      targetDiagramType = diagramType,
      targetScenario = selectedScenario,
      silent = false,
    } = options;

    if (!targetDocument) {
      toast.error('Please select a document first');
      return;
    }
    
    setGenerating(true);
    setError(null);
    
    try {
      const response = await ieeeDiagramsAPI.generateDiagram(
        targetDocument,
        targetDiagramType,
        targetDiagramType === 'sequence' ? (targetScenario || null) : null
      );
      
      const data = response.data;
      
      if (data.success) {
        setCurrentDiagram({
          mermaid_syntax: data.mermaid_syntax,
          plantuml_syntax: data.plantuml_syntax, 
          diagram_id: data.diagram_id,
        });
        if (!silent) {
          toast.success(`IEEE-compliant ${targetDiagramType} diagram generated successfully`);
        }
        
        if (data.compliance?.warning && !silent) toast.warning(data.compliance.warning);
      } else {
        setError(data.error || 'Failed to generate diagram');
        if (!silent) toast.error(data.error || 'Failed to generate diagram');
      }
    } catch (err) {
      setError('Failed to generate diagram. Please try again.');
      if (!silent) toast.error('Could not generate diagram');
    } finally {
      setGenerating(false);
    }
  };

  useEffect(() => {
    if (!isTraceabilityDeepLink || !selectedDocument) return;

    const autoKey = [
      selectedDocument,
      diagramType,
      selectedScenario || 'default',
      deepLinkHighlight || 'none',
      deepLinkNodeType || 'node',
    ].join('|');

    if (autoGeneratedDeepLinkRef.current === autoKey) return;

    if (diagramType === 'sequence' && scenarios.length > 0 && !selectedScenario) {
      return;
    }

    autoGeneratedDeepLinkRef.current = autoKey;

    handleGenerateDiagram({
      targetDocument: selectedDocument,
      targetDiagramType: diagramType,
      targetScenario: selectedScenario,
      silent: true,
    });
  }, [
    isTraceabilityDeepLink,
    selectedDocument,
    diagramType,
    selectedScenario,
    scenarios.length,
    deepLinkHighlight,
    deepLinkNodeType,
  ]);

  const handleDocumentChange = (e) => {
    const docId = e.target.value;
    setSelectedDocument(docId);
    navigate(`/visualization/${docId}`);
  };

  const handleZoomIn = () => setZoomLevel(prev => Math.min(prev + 10, 200));
  const handleZoomOut = () => setZoomLevel(prev => Math.max(prev - 10, 50));
  const handleResetZoom = () => setZoomLevel(100);

  // --- Export Handlers ---
  const handleExportPlantUML = async () => {
    if (!currentDiagram?.plantuml_syntax) return toast.error('No PlantUML syntax to export');
    try {
      const blob = new Blob([currentDiagram.plantuml_syntax], { type: 'text/plain;charset=utf-8' });
      const downloadUrl = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = downloadUrl;
      a.download = `${diagramType}_diagram.puml`;
      a.click();
      URL.revokeObjectURL(downloadUrl);
      toast.success('PlantUML source exported successfully');
    } catch (err) {
      toast.error('Failed to export PlantUML source');
    }
  };

 const handleExportSVG = async () => {
    if (!currentDiagram?.plantuml_syntax) return toast.error('No diagram to export');
    
    try {
      const toastId = toast.loading('Generating SVG...');

      const encoded = plantumlEncoder.encode(currentDiagram.plantuml_syntax);
      const response = await ieeeDiagramsAPI.renderPlantUMLToSVG(encoded);
      const blob = new Blob([response.data], { type: 'image/svg+xml;charset=utf-8' });
      const downloadUrl = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = downloadUrl;
      a.download = `${diagramType}_diagram.svg`;
      a.click();
      URL.revokeObjectURL(downloadUrl);
      
      toast.success('SVG exported successfully', { id: toastId });
    } catch (err) {
      console.error('SVG export failed:', err);
      toast.error('Failed to export SVG');
    }
  };

  const currentDiagramString = currentDiagram?.plantuml_syntax || '';

  // Listen for node clicks emitted by DiagramViewer
  useEffect(() => {
    const handler = async (evt) => {
      const elementId = evt?.detail?.elementId;
      if (!elementId || !currentDiagram?.diagram_id) return;

      try {
        const res = await ieeeDiagramsAPI.getDiagramNodeRequirements(
          currentDiagram.diagram_id,
          elementId
        );

        const requirements = res?.data?.requirements || [];
        setLinkedRequirements(requirements);
        setShowNodeRequirementsModal(true);
      } catch (err) {
        console.error('Failed to load linked requirements for diagram node:', err);
        toast.error('Failed to load linked requirements');
      }
    };

    window.addEventListener('diagram-node-click', handler);
    return () => window.removeEventListener('diagram-node-click', handler);
  }, [currentDiagram?.diagram_id]);

  return (

    <div className="min-h-screen bg-gray-50 dark:bg-gray-950 py-8">

      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
        
        {/* --- Top Header --- */}
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between mb-8 gap-4">
          <div className="flex items-center gap-4">
            <button
              onClick={() => navigate('/analysis-results')}
              className="p-2 bg-white dark:bg-gray-900 rounded-full border border-gray-200 dark:border-gray-700 shadow-sm hover:bg-gray-50 dark:hover:bg-gray-800 text-gray-600 dark:text-gray-300 transition-all"

            >
              <ArrowLeft className="w-5 h-5" />
            </button>
            <div>
              <h1 className="text-2xl font-bold text-gray-900 tracking-tight">Visualization</h1>
              <p className="text-sm text-gray-500 mt-0.5">Generate and export IEEE-compliant diagrams</p>
            </div>
          </div>
          
          <div className="flex gap-3 w-full sm:w-auto">
            <button
              onClick={handleExportSVG}
              disabled={!currentDiagramString}
              className="flex-1 sm:flex-none flex items-center justify-center px-4 py-2 bg-white border border-gray-300 text-gray-700 rounded-lg hover:bg-gray-50 disabled:opacity-50 disabled:cursor-not-allowed transition-all text-sm font-medium shadow-sm"
            >
              <Download className="w-4 h-4 mr-2" />
              SVG
            </button>
            <button
              onClick={handleExportPlantUML}
              disabled={!currentDiagramString}
              className="flex-1 sm:flex-none flex items-center justify-center px-4 py-2 bg-white border border-gray-300 text-gray-700 rounded-lg hover:bg-gray-50 disabled:opacity-50 disabled:cursor-not-allowed transition-all text-sm font-medium shadow-sm"
            >
              <Download className="w-4 h-4 mr-2" />
              PlantUML
            </button>
          </div>
        </div>

        {/* --- Document Selector --- */}
        {!selectedDocument && (
        <div className="bg-white dark:bg-gray-900 rounded-xl shadow-sm border border-gray-200 dark:border-gray-700 p-6 mb-6">

            <div className="flex items-center gap-3 mb-4">
              <div className="p-2 bg-blue-50 rounded-lg">
                <FileText className="h-5 w-5 text-blue-600" />
              </div>
              <h3 className="text-lg font-semibold text-gray-900 dark:text-gray-100">Select a Source Document</h3>

            </div>
            <select
              value={selectedDocument}
              onChange={handleDocumentChange}
              className="w-full md:w-1/2 px-4 py-2.5 bg-gray-50 border border-gray-200 rounded-lg text-gray-900 focus:outline-none focus:ring-2 focus:ring-blue-500 focus:bg-white transition-all"
            >
              <option value="">Choose document...</option>
              {documents.map((doc) => (
                <option key={doc.doc_id} value={doc.doc_id}>{doc.filename}</option>
              ))}
            </select>
          </div>
        )}

        {/* --- Control Bar --- */}
        <div className="bg-white rounded-xl shadow-sm border border-gray-200 p-4 mb-6">
          <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-4">
            
            <div className="flex flex-wrap items-center gap-4">
              {/* Diagram Toggles */}
              <div className="flex bg-gray-100 p-1 rounded-lg">
                <button
                    onClick={() => {
                      setDiagramType('usecase');
                      autoGeneratedDeepLinkRef.current = '';
                    }}
                  className={`px-4 py-2 rounded-md text-sm font-medium transition-all ${
                    diagramType === 'usecase'
                      ? 'bg-white text-blue-700 shadow-sm'
                      : 'text-gray-600 hover:text-gray-900'
                  }`}
                >
                  Use Case
                </button>
                <button
                    onClick={() => {
                      setDiagramType('sequence');
                      autoGeneratedDeepLinkRef.current = '';
                    }}
                  className={`px-4 py-2 rounded-md text-sm font-medium transition-all ${
                    diagramType === 'sequence'
                      ? 'bg-white text-blue-700 shadow-sm'
                      : 'text-gray-600 hover:text-gray-900'
                  }`}
                >
                  Sequence
                </button>
              </div>

              {/* Scenario Dropdown (Conditional) */}
              {diagramType === 'sequence' && scenarios.length > 0 && (
                <div className="flex items-center gap-2">
                  <Filter className="h-4 w-4 text-gray-400" />
                  <div className="relative">
                    <select
                      value={selectedScenario}
                      onChange={(e) => setSelectedScenario(e.target.value)}
                      className="appearance-none bg-gray-50 border border-gray-200 rounded-lg px-4 py-2 pr-8 text-sm text-gray-700 focus:ring-2 focus:ring-blue-500 focus:outline-none min-w-[200px]"
                    >
                      {scenarios.map(sc => (
                        <option key={sc.id} value={sc.id}>
                          {sc.name} ({sc.steps || '?'} steps)
                        </option>
                      ))}
                    </select>
                    <ChevronDown className="absolute right-2 top-1/2 -translate-y-1/2 h-4 w-4 text-gray-400 pointer-events-none" />
                  </div>
                </div>
              )}

              {/* Primary Generate Action */}
              <button
                onClick={() => {
                  autoGeneratedDeepLinkRef.current = '';
                  handleGenerateDiagram();
                }}
                disabled={generating || !selectedDocument}
                className="flex items-center px-5 py-2 bg-blue-600 text-white text-sm font-medium rounded-lg hover:bg-blue-700 disabled:opacity-50 disabled:cursor-not-allowed transition-all shadow-sm"
              >
                {generating ? (
                  <span className="flex items-center">
                    <div className="w-4 h-4 border-2 border-white/30 border-t-white rounded-full animate-spin mr-2" />
                    Generating...
                  </span>
                ) : (
                  <span className="flex items-center">
                    <Play className="w-4 h-4 mr-2" />
                    Generate Diagram
                  </span>
                )}
              </button>
            </div>

            {/* Zoom Controls */}
            <div className="flex items-center gap-1 border-l border-gray-200 pl-4">
              <button onClick={handleZoomOut} className="p-2 text-gray-500 hover:bg-gray-100 rounded-lg transition-colors" title="Zoom Out">
                <ZoomOut className="h-4 w-4" />
              </button>
              <span className="text-xs font-medium text-gray-600 w-12 text-center">{zoomLevel}%</span>
              <button onClick={handleZoomIn} className="p-2 text-gray-500 hover:bg-gray-100 rounded-lg transition-colors" title="Zoom In">
                <ZoomIn className="h-4 w-4" />
              </button>
              <button onClick={handleResetZoom} className="p-2 text-gray-500 hover:bg-gray-100 rounded-lg transition-colors ml-1" title="Reset Zoom">
                <RotateCcw className="h-4 w-4" />
              </button>
            </div>

          </div>
        </div>

        {/* --- Diagram Canvas --- */}
        <div className="bg-white rounded-xl shadow-sm border border-gray-200 overflow-hidden flex flex-col min-h-[600px]">
          
          {/* Canvas Header */}
          <div className="px-6 py-4 border-b border-gray-100 flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-gray-50/50">
            <h2 className="text-lg font-semibold text-gray-900">
              {diagramType === 'sequence'
                ? (selectedScenario ? `Sequence: ${selectedScenario}` : 'Sequence Diagram')
                : 'Use Case Diagram'}
            </h2>
            {deepLinkHighlight && (
              <div className="inline-flex items-center gap-2 rounded-full border border-blue-200 bg-blue-50 px-3 py-1.5 text-xs font-medium text-blue-800">
                <span>Focused element: {deepLinkHighlight}</span>
                <button
                  type="button"
                  onClick={() => navigate(location.pathname)}
                  className="rounded-full px-2 py-0.5 text-blue-700 hover:bg-blue-100"
                >
                  Clear
                </button>
              </div>
            )}
          </div>

          {/* Canvas Area */}
          <div className="flex-1 p-8 flex items-center justify-center bg-dots-pattern bg-gray-50/30 overflow-auto relative">
            {generating ? (
              <div className="flex flex-col items-center justify-center space-y-4">
                <div className="w-10 h-10 border-4 border-blue-100 border-t-blue-600 rounded-full animate-spin" />
                <p className="text-sm font-medium text-gray-500">Synthesizing IEEE-compliant diagram...</p>
              </div>
            ) : error ? (
              <div className="flex flex-col items-center max-w-sm text-center">
                <div className="w-12 h-12 bg-red-50 text-red-500 rounded-full flex items-center justify-center mb-4">
                  <AlertTriangle className="h-6 w-6" />
                </div>
                <h3 className="text-gray-900 font-medium mb-1">Generation Failed</h3>
                <p className="text-sm text-gray-500 mb-6">{error}</p>
                <button onClick={handleGenerateDiagram} className="px-4 py-2 bg-white border border-gray-300 text-gray-700 text-sm font-medium rounded-lg hover:bg-gray-50">
                  Try Again
                </button>
              </div>
            ) : !selectedDocument ? (
              <div className="flex flex-col items-center text-gray-400">
                <FileText className="h-16 w-16 mb-4 opacity-20" />
                <p className="text-sm font-medium">Select a document above to begin</p>
              </div>
            ) : currentDiagramString ? (
              <div className="w-full h-full flex items-center justify-center">
                <DiagramViewer
                  key={`${diagramType}-${selectedScenario || 'usecase'}`}
                  chartString={currentDiagramString}
                  zoomLevel={zoomLevel}
                  darkMode={false}
                />
              </div>
            ) : (
              <div className="flex flex-col items-center text-gray-400">
                <div className="w-16 h-16 border-2 border-dashed border-gray-300 rounded-xl mb-4 flex items-center justify-center bg-gray-50">
                  <Play className="h-6 w-6 text-gray-300" />
                </div>
                <p className="text-sm font-medium text-gray-500">Ready to visualize. Click "Generate Diagram" to start.</p>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};

export default VisualizationPage;